def build_paper(paper_id, title, subject, questions, source):
    return {
        "paper_id": paper_id,
        "title": title,
        "subject": subject,
        "year": 2026,
        "session": "网络模考",
        "source": source,
        "total_questions": len(questions),
        "questions": [reform_linter(q) for q in questions]
    }

def sync_deck_anki(deck_name, questions, subject, paper_title):
    model_name = "银行从业·全真机考客观题"
    anki_invoke("createDeck", deck=deck_name)

    notes = []
    for q in questions:
        fields = {
            "ID": q["id"],
            "题型": q["type"],
            "题干": q["question"],
            "选项A": q["options"].get("A", ""),
            "选项B": q["options"].get("B", ""),
            "选项C": q["options"].get("C", ""),
            "选项D": q["options"].get("D", ""),
            "选项E": q["options"].get("E", ""),
            "正确答案": q["answer"],
            "核心考点解析": q["explanation"],
            "速记口诀": q["mnemonic"],
            "避坑指南": q["trap"]
        }
        notes.append({
            "deckName": deck_name,
            "modelName": model_name,
            "fields": fields,
            "tags": ["2026银行从业", subject, "网络模考卷", q["type"]]
        })

    existing = anki_invoke("findCards", query=f'deck:"{deck_name}"')
    if existing:
        print(f"   ⚠️ 牌组 '{deck_name}' 已存在 {len(existing)} 张卡片，清理旧版本...")
        anki_invoke("deleteDecks", decks=[deck_name], cardsToo=True)
        anki_invoke("createDeck", deck=deck_name)

    print(f"   🚀 正在注入 {len(notes)} 张卡片至 Anki 牌组...")
    added = anki_invoke("addNotes", notes=notes)
    success = sum(1 for x in added if x is not None)
    print(f"   ✅ 成功注入: {success} / {len(notes)} 张卡片！")
    return success

