def anki_invoke(action, **params):
    req = urllib.request.Request(
        "http://127.0.0.1:8765",
        json.dumps({"action": action, "version": 6, "params": params}).encode("utf-8"),
        headers={"Content-Type": "application/json"}
    )
    with urllib.request.urlopen(req) as resp:
        res = json.loads(resp.read().decode("utf-8"))
        if len(res) == 2 and "error" in res and res["error"] is not None:
            raise Exception(res["error"])
        return res["result"]

def push_questions_to_anki(deck_name, questions):
    model_name = "银行从业·全真机考客观题"
    notes = []
    for q in questions:
        opt_a = q["options"].get("A", "")
        opt_b = q["options"].get("B", "")
        opt_c = q["options"].get("C", "")
        opt_d = q["options"].get("D", "")
        opt_e = q["options"].get("E", "")
        
        fields = {
            "ID": q["id"],
            "题型": q["type"],
            "题干": q["question"],
            "选项A": opt_a,
            "选项B": opt_b,
            "选项C": opt_c,
            "选项D": opt_d,
            "选项E": opt_e,
            "正确答案": q["answer"],
            "核心考点解析": q["explanation"],
            "速记口诀": q["mnemonic"],
            "避坑指南": q["trap"]
        }
        
        notes.append({
            "deckName": deck_name,
            "modelName": model_name,
            "fields": fields,
            "tags": ["2026银行从业", "全真机考", q["type"]]
        })
    
    # Check if notes already exist in this deck to avoid duplicates
    existing_cards = anki_invoke("findCards", query=f'deck:"{deck_name}"')
    if existing_cards:
        print(f"⚠️ 牌组 '{deck_name}' 中已存在 {len(existing_cards)} 张卡片，先清理旧卡以注入最新卡片...")
        anki_invoke("deleteDecks", decks=[deck_name], cardsToo=True)
        anki_invoke("createDeck", deck=deck_name)
    
    print(f"🚀 正在向 '{deck_name}' 批量注入 {len(notes)} 道机考题目...")
    added_ids = anki_invoke("addNotes", notes=notes)
    success_count = sum(1 for x in added_ids if x is not None)
    print(f"✅ 成功注入 {success_count} / {len(notes)} 张卡片！")
    return success_count

